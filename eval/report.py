"""Build eval/results/RESULTS.md from the JSON result files (no numbers are typed by hand)."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "eval" / "results"


def ms(v):
    return "–" if v is None else f"{v * 1000:.0f}"


def pc(v):
    return "–" if v is None else f"{v * 100:.1f}%"


def eval_table(path: Path) -> str:
    d = json.loads(path.read_text(encoding="utf-8"))["summary"]
    lines = [f"### `{d['mode']}` — n={d['n']}, STT={d.get('stt_model')} ({d.get('stt_device')}), "
             f"LLM={','.join(d.get('llm_providers_used', []))}, run {d.get('run_at')}", "",
             "| lang | n | WER | CER | detected-lang acc | tool acc | answer acc | reply-in-lang | errors |",
             "|---|---|---|---|---|---|---|---|---|"]
    for k, v in [*d["per_lang"].items(), ("**all**", d["overall"])]:
        lines.append(f"| {k} | {v['n']} | {pc(v.get('wer'))} | {pc(v.get('cer'))} | {pc(v['detected_lang_acc'])} | "
                     f"{pc(v['tool_acc'])} | {pc(v['answer_acc'])} | {pc(v['reply_lang_acc'])} | {v['errors']} |")
    lines += ["", "| lang | STT p50/p95 ms | LLM TTFT p50/p95 ms | TTS first audio p50/p95 ms | "
                  "**E2E to first audio p50/p95 ms** | total turn p50/p95 ms |", "|---|---|---|---|---|---|"]
    for k, v in [*d["per_lang"].items(), ("**all**", d["overall"])]:
        cells = [f"{ms(v[key]['p50'])} / {ms(v[key]['p95'])}"
                 for key in ("stt_s", "llm_ttft_s", "tts_first_audio_s", "e2e_first_audio_s", "total_s")]
        lines.append(f"| {k} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def stt_table() -> str:
    p = RES / "stt_bench.json"
    if not p.exists():
        return ""
    d = json.loads(p.read_text(encoding="utf-8"))
    lines = ["| model | lang mode | hi WER | hi CER | kn WER | kn CER | en WER | en CER | kn LID acc | "
             "STT p50 ms (hi/kn/en) |", "|---|---|---|---|---|---|---|---|---|---|"]
    for name, r in d.items():
        pl = r["per_lang"]
        lines.append(f"| {name.split('+')[0]} | {'forced' if r.get('forced_language') else 'auto-detect'} | "
                     f"{pc(pl['hi']['wer'])} | {pc(pl['hi']['cer'])} | {pc(pl['kn']['wer'])} | {pc(pl['kn']['cer'])} | "
                     f"{pc(pl['en']['wer'])} | {pc(pl['en']['cer'])} | {pc(pl['kn']['lid_acc_final'])} | "
                     f"{ms(pl['hi']['stt_p50_s'])}/{ms(pl['kn']['stt_p50_s'])}/{ms(pl['en']['stt_p50_s'])} |")
    return "\n".join(lines)


def main() -> None:
    parts = ["# Eval results (auto-generated by eval/report.py)", "",
             "42 scripted utterances (14 hi, 14 kn, 14 en), synthesized with edge-tts using 2 voices per language; "
             "every 3rd clip has white noise at 15 dB SNR. Eval date pinned to 2026-10-04 10:00 for reminders.", "",
             "## STT model comparison (faster-whisper, RTX 4060, float16)", "", stt_table(), ""]
    for name in ("eval_audio.json", "eval_audio_pinned.json", "eval_text.json"):
        if (RES / name).exists():
            parts += ["## End-to-end: " + name, "", eval_table(RES / name), ""]
    e2e = RES / "e2e_browser.json"
    if e2e.exists():
        parts += ["## Browser E2E (Playwright, Chromium fake microphone)", "",
                  "| lang | transcript | detected | tool | audio clips played | E2E first audio ms |", "|---|---|---|---|---|---|"]
        for r in json.loads(e2e.read_text(encoding="utf-8")):
            parts.append(f"| {r['lang']} | {r['transcript']} | {r['detected_language']} | "
                         f"{', '.join(t['name'] for t in r['tool_calls'])} | {r['audio_clips_played']} | "
                         f"{ms(r['timings'].get('e2e_first_audio_s'))} |")
    (RES / "RESULTS.md").write_text("\n".join(parts) + "\n", encoding="utf-8")
    print((RES / "RESULTS.md").read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
